const waitUntil = async (check: () => boolean, ms = 10_000) => {
  const deadline = Date.now() + ms;
  while (!check()) {
    if (Date.now() > deadline) throw new Error("condition not met in time");
    await new Promise((resolve) => setTimeout(resolve, 25));
  }
};

test("talking to Claude in its own session shows up in the room; @codex there wakes Codex, who sees it", async () => {
  const room = createTestRoom({
    rules: [{ agent: "codex", match: "check the units", reply: "@claude units look fine to me", once: true }],
  });
  try {
    room.engine.postHuman("Hello both");
    await withTimeout(room.engine.waitIdle());
    const claudeSession = room.store.state.sessions.claude!.sessionId;
    const file = locateNativeSession("claude", claudeSession, room.store.state.workspace, room.env)!;
    assert.ok(file, "the fake claude wrote its native session");
    // Agoryx's own turns are never imported back.
    assert.equal(room.store.state.messages.filter((message) => message.native).length, 0);

    const runsBefore = room.store.state.runs.length;
    appendFileSync(
      file,
      jsonl([
        cUser("Quick question just for you: is the parser safe?", { origin: { kind: "human" } }),
        cAssistant([text("Yes, it only reads complete lines.")], "end_turn"),
      ]),
    );
    await waitUntil(() => room.store.state.messages.filter((message) => message.native).length === 2);
    const quiet = room.store.state.messages.filter((message) => message.native);
    assert.deepEqual(quiet.map((message) => [message.author, message.kind, message.wakes]), [
      ["Ivan", "human", false],
      ["claude", "agent", false],
    ]);
    assert.equal(quiet[0]!.native!.agent, "claude");
    assert.equal(room.store.state.runs.length, runsBefore, "a side conversation does not start a run");

    appendFileSync(
      file,
      jsonl([
        cUser("@codex can you check the units?", { origin: { kind: "human" } }),
        cAssistant([text("Asking Codex to double-check the units.")], "end_turn"),
      ]),
    );
    await waitUntil(() => room.store.state.runs.length > runsBefore);
    await withTimeout(room.engine.waitIdle());

    const codexPrompt = room.invocations("codex").at(-1)!.prompt!;
    assert.match(codexPrompt, /Ivan \(human\) → Claude, directly in Claude's own session/);
    assert.match(codexPrompt, /check the units/);
    assert.match(codexPrompt, /Asking Codex to double-check/);
    assert.match(codexPrompt, /is the parser safe\?/, "the earlier side conversation reaches Codex too");

    // Codex addressed Claude; Claude's delta has Codex's reply but not what is already in its session.
    const claudePrompt = room.invocations("claude").at(-1)!.prompt!;
    assert.match(claudePrompt, /units look fine to me/);
    assert.doesNotMatch(claudePrompt, /check the units\?/);
    assert.doesNotMatch(claudePrompt, /is the parser safe/);
    assert.equal(room.store.state.messages.filter((message) => message.native).length, 4);
  } finally {
    await room.cleanup();
  }
});

