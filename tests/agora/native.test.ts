const xEvent = (payload: Record<string, unknown>) => ({ timestamp: ts(), type: "event_msg", payload });
const xItem = (turn: string, item: Record<string, unknown>) => xEvent({ type: "item_completed", turn_id: turn, item });
const xTurn = (turn: string, prompt: string, answer: string | null, end: "complete" | "aborted" | null = "complete") => [
  xEvent({ type: "task_started", turn_id: turn }),
  { timestamp: ts(), type: "response_item", payload: { type: "message", role: "developer", content: [{ type: "input_text", text: "## Memory" }] } },
  { timestamp: ts(), type: "response_item", payload: { type: "message", role: "user", content: [{ type: "input_text", text: "<environment_context>cwd</environment_context>" }] } },
  xItem(turn, { type: "UserMessage", content: [{ type: "text", text: prompt }] }),
  xItem(turn, { type: "AgentMessage", phase: "commentary", content: [{ type: "Text", text: "Looking…" }] }),
  ...(answer ? [xItem(turn, { type: "AgentMessage", phase: "final_answer", content: [{ type: "Text", text: answer }] })] : []),
  ...(end === "complete" ? [xEvent({ type: "task_complete", turn_id: turn, last_agent_message: answer })] : []),
  ...(end === "aborted" ? [xEvent({ type: "turn_aborted", turn_id: turn, reason: "interrupted" })] : []),
];

